import { test, expect } from '@playwright/test';

test('independent access routes, error recovery, browser history and login', async ({ page }, testInfo) => {
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/#/login');
  await expect(page.locator('.sidebar')).toHaveCount(0);
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Qué bueno verte de nuevo.');
  await expect(page.getByRole('heading', { level: 1 })).toBeFocused();
  await page.getByLabel('Tema de la aplicación').selectOption('light');
  await expect(page.locator('.auth-header img')).toHaveJSProperty('naturalWidth', 512);
  await page.screenshot({ path: testInfo.outputPath('login-claro.png'), fullPage: true });
  await page.getByLabel('Tema de la aplicación').selectOption('dark');
  await page.screenshot({ path: testInfo.outputPath('login-oscuro.png'), fullPage: true });
  await page.getByPlaceholder('vecino@ejemplo.com').fill('admin@browser.test');
  await page.getByPlaceholder('Tu contraseña').fill('Incorrecta123!');
  await page.getByRole('button', { name: 'Mostrar contraseña' }).click();
  await expect(page.getByPlaceholder('Tu contraseña')).toHaveAttribute('type', 'text');
  await page.getByRole('button', { name: 'Entrar a mi comunidad' }).click();
  await expect(page.getByRole('alert')).toContainText('Correo o contraseña incorrectos.');
  await page.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
  await expect(page).toHaveURL(/#\/registro$/);
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(page.getByPlaceholder('Al menos 8 caracteres')).toHaveValue('');
  await expect(page.getByPlaceholder('Al menos 8 caracteres')).toHaveAttribute('type', 'password');
  await page.reload();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Tu barrio empieza contigo.');
  await page.screenshot({ path: testInfo.outputPath('registro-oscuro.png'), fullPage: true });
  await page.goBack();
  await expect(page).toHaveURL(/#\/login$/);
  await expect(page.getByPlaceholder('¿Cómo te llamas?')).toHaveCount(0);
  await page.getByPlaceholder('vecino@ejemplo.com').fill('admin@browser.test');
  await page.getByPlaceholder('Tu contraseña').fill('PruebaAdmin123!');
  await page.getByRole('button', { name: 'Entrar a mi comunidad' }).click();
  await expect(page.getByRole('heading', { name: 'Una comunidad mejor atendida' })).toBeVisible();
  expect(errors).toEqual([]);
});

test('mobile registration, return navigation and reversible background preference', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/#/registro');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Tu barrio empieza contigo.');
  await expect(page.getByRole('button', { name: 'Volver a la comunidad', exact: true })).toBeVisible();
  for (const width of [320, 390, 768, 1024]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel('Tema de la aplicación').selectOption('dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.screenshot({ path: testInfo.outputPath('registro-movil-oscuro.png'), fullPage: true });
  await page.getByLabel('Tema de la aplicación').selectOption('light');
  await page.screenshot({ path: testInfo.outputPath('registro-movil.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Volver a la comunidad', exact: true }).click();
  await page.getByRole('button', { name: 'Crear nuevo reporte', exact: true }).click();
  await expect(page).toHaveURL(/#\/login$/);
  await page.getByRole('button', { name: 'Volver a la comunidad', exact: true }).click();
  await page.goto('/#/registro');
  await page.getByPlaceholder('¿Cómo te llamas?').fill('María Diseño');
  await page.getByPlaceholder('vecino@ejemplo.com').fill('maria.design@browser.test');
  await page.getByPlaceholder('Al menos 8 caracteres').fill('PruebaVecinal123!');
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Tu comunidad, al día', exact: true })).toBeVisible();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Abrir mi cuenta' }).click();
  await expect(page.getByRole('heading', { name: 'María Diseño', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Liso', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-background', 'plain');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-background', 'plain');
  await page.getByRole('button', { name: 'Abrir mi cuenta' }).click();
  await expect(page.getByRole('button', { name: 'Liso', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Degradado', exact: true }).click();
  await page.getByLabel('Tema de la aplicación').last().selectOption('dark');
  await expect(page.locator('html')).toHaveAttribute('data-background', 'gradient');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('preferencias-movil.png'), fullPage: true });
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
});
